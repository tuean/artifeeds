#!/usr/bin/env python3
"""Measure the app's CPU under controlled configurations.

    scripts/bench_cpu.py label [--seconds 12] [--sources N] [--set key=value]...

Runs the release binary against a *copy* of the live database, so the scheduler
starts from the same health, etags and backoff the real app has — a cold database
would measure a first sweep instead of steady state. Each run gets its own data
directory (`ARTIFEEDS_DATA_DIR`) and its own config, so runs cannot contaminate
each other or the installed app.

`--sources N` writes a config with only the first N sources: the difference
between N=1404 and N=2 is the sweep's share of the CPU, with the same UI running
in both.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import shutil
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
BIN = pathlib.Path(os.environ.get("AF_BENCH_BIN", ROOT / "target/release/artifeeds-app"))
LIVE = pathlib.Path.home() / "Library/Application Support/Artifeeds"
WORK = pathlib.Path("/tmp/af-bench")


def cpu_seconds(pid: int) -> float | None:
    out = subprocess.run(["ps", "-o", "time=", "-p", str(pid)], capture_output=True, text=True).stdout.strip()
    if not out:
        return None
    days = 0
    if "-" in out:
        d, out = out.split("-", 1)
        days = int(d)
    parts = [float(p) for p in out.split(":")]
    while len(parts) < 3:
        parts.insert(0, 0.0)
    h, m, s = parts
    return days * 86400 + h * 3600 + m * 60 + s


def settings_block(overrides: dict[str, str]) -> str:
    base = {
        "global_concurrency": "24",
        "per_host_concurrency": "2",
        "max_concurrent_fetches": "24",
        "default_interval_secs": "1800",
        "min_interval_secs": "900",
        "max_interval_secs": "86400",
        "startup_spread_secs": "45",
        "max_in_memory_articles": "20000",
        "retention_days": "120",
        "max_entries_per_fetch": "60",
        "preview_chars": "400",
        "max_content_bytes": "65536",
        "connect_timeout_secs": "5",
        "request_timeout_secs": "30",
        "max_body_bytes": "16777216",
    }
    base.update(overrides)
    lines = ["[settings]"]
    for key, value in base.items():
        lines.append(f"{key} = {value}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("label")
    parser.add_argument("--seconds", type=int, default=12)
    parser.add_argument("--sources", type=int, default=0, help="0 = every configured source")
    parser.add_argument("--settle", type=int, default=25, help="seconds before measuring")
    parser.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    parser.add_argument("--disable-sources", action="store_true", help="mark every source disabled: measures the UI and store alone")
    args = parser.parse_args()

    overrides = {}
    for pair in args.set:
        key, _, value = pair.partition("=")
        overrides[key.strip()] = value.strip()

    work = WORK / args.label.replace(" ", "_")
    if work.exists():
        shutil.rmtree(work)
    (work / "data").mkdir(parents=True)
    (work / "config").mkdir(parents=True)

    # Seed the data directory with the live database so the scheduler state — and
    # therefore the work — matches the real app.
    for name in ("artifeeds.db", "artifeeds.db-wal", "artifeeds.db-shm"):
        src = LIVE / name
        if src.exists():
            shutil.copy2(src, work / "data" / name)
    for name in ("zhihu.cookies",):
        src = LIVE / name
        if src.exists():
            shutil.copy2(src, work / "data" / name)

    # Sources: the live feed files, optionally truncated to the first N.
    feeds = work / "config/feeds"
    feeds.mkdir()
    taken = 0
    for src in sorted((LIVE / "feeds").glob("*.toml")):
        text = src.read_text()
        if args.sources:
            blocks = text.split("[[sources]]")
            kept = [blocks[0]]
            for block in blocks[1:]:
                if taken >= args.sources:
                    break
                kept.append(block)
                taken += 1
            text = "[[sources]]".join(kept)
        if args.disable_sources:
            # `enabled = false` keeps every source out of the sweep while the
            # sidebar and list still render the whole fleet.
            text = text.replace("[[sources]]", "[[sources]]\nenabled = false")
        (feeds / src.name).write_text(text)

    config = work / "config/feeds.toml"
    config.write_text(
        "# generated by scripts/bench_cpu.py\n"
        f'include = ["{feeds}"]\n\n' + settings_block(overrides)
    )

    env = dict(os.environ)
    env["ARTIFEEDS_DATA_DIR"] = str(work / "data")
    env["RUST_LOG"] = "info"
    log = (work / "app.log").open("w")
    proc = subprocess.Popen([str(BIN), str(config)], env=env, stdout=log, stderr=subprocess.STDOUT)

    try:
        time.sleep(args.settle)
        if proc.poll() is not None:
            print(f"{args.label}: exited early, see {work}/app.log")
            return 1
        before = cpu_seconds(proc.pid)
        time.sleep(args.seconds)
        after = cpu_seconds(proc.pid)
        if before is None or after is None:
            print(f"{args.label}: process vanished")
            return 1
        cores = (after - before) / args.seconds
        sources = subprocess.run(
            ["grep", "-c", "^\\[\\[sources\\]\\]", "-r", str(feeds)],
            capture_output=True, text=True,
        ).stdout
        print(f"{args.label:26} {cores * 100:7.1f}% of one core   ({cores:.2f} cores)")
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            proc.kill()
        log.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
